// build-content.mjs — compile content/**/*.md into the three views the site needs:
//   lib/content-index.json                 → static generation (pages embed full markdown)
//   public/docs-content.json               → client-side search index (titles + text)
//   netlify/functions/_data/docs-data.mjs  → bundled data for GET /api/docs
//
// Frontmatter (optional): title, description. Everything else (guide, slug, order)
// is derived from the directory + filename so adding a page is a pure file drop.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "content");

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name.endsWith(".md")) out.push(p);
  }
  return out;
}

function parseFrontmatter(text) {
  let title = "", description = "", body = text;
  if (text.startsWith("---")) {
    const end = text.indexOf("\n---", 3);
    if (end !== -1) {
      const fm = text.slice(3, end);
      body = text.slice(end + 4).replace(/^\s*\n/, "");
      for (const line of fm.split("\n")) {
        const m = line.match(/^(\w+)\s*:\s*(.+)$/);
        if (!m) continue;
        if (m[1] === "title") title = m[2].trim().replace(/^["']|["']$/g, "");
        if (m[1] === "description") description = m[2].trim().replace(/^["']|["']$/g, "");
      }
    }
  }
  if (!title) {
    const h1 = body.match(/^#\s+(.+)$/m);
    title = h1 ? h1[1].trim() : "Untitled";
  }
  if (!description) {
    const firstPara = body.split(/\n\s*\n/).find(p => p && !p.startsWith("#") && !p.startsWith("```"));
    description = firstPara ? firstPara.replace(/[#*`>\[\]]/g, "").trim().slice(0, 160) : "";
  }
  return { title, description, body };
}

const files = walk(CONTENT);
const docs = [];
for (const path of files) {
  const rel = path.slice(CONTENT.length + 1).replace(/\.md$/, ""); // e.g. developers/01-install-mz
  const guide = rel.split("/")[0];
  const fname = rel.split("/").pop(); // 01-install-mz
  const m = fname.match(/^(\d+)-(.+)$/);
  const order = m ? parseInt(m[1], 10) : 99;
  const slug = `${guide}/${m ? m[2] : fname}`;
  const raw = readFileSync(path, "utf8");
  const { title, description, body } = parseFrontmatter(raw);
  const words = body.split(/\s+/).filter(Boolean).length;
  docs.push({ slug, guide, order, title, description, words, content: body });
}

docs.sort((a, b) => (a.guide === b.guide ? a.order - b.order : a.guide.localeCompare(b.guide)));

// 1. SSG index (with full content embedded)
mkdirSync(join(ROOT, "lib"), { recursive: true });
writeFileSync(join(ROOT, "lib", "content-index.json"),
  JSON.stringify({ generated: new Date().toISOString(), guides: ["developers", "users"], docs }, null, 2));

// 2. Client search index (no full content bodies — excerpt + plain text)
const stripMd = (t) => t
  .replace(/```[\s\S]*?```/g, " ")
  .replace(/`([^`]*)`/g, "$1")
  .replace(/!\[([^\]]*)\]\(([^)]*)\)/g, "$1")
  .replace(/\[([^\]]*)\]\(([^)]*)\)/g, "$1")
  .replace(/[#>*_|-]{2,}/g, " ")
  .replace(/\s+/g, " ")
  .trim();
writeFileSync(join(ROOT, "public", "docs-content.json"),
  JSON.stringify({
    generated: new Date().toISOString(),
    docs: docs.map(d => ({
      slug: d.slug, guide: d.guide, title: d.title,
      description: d.description,
      text: stripMd(d.content).slice(0, 20000)
    }))
  }));

// 3. Bundled module for /api/docs (full markdown for LLM readers)
const fnDataDir = join(ROOT, "netlify", "functions", "_data");
mkdirSync(fnDataDir, { recursive: true });
writeFileSync(join(fnDataDir, "docs-data.mjs"),
  "// Generated by scripts/build-content.mjs — do not edit by hand.\n" +
  `export const DOCS = ${JSON.stringify(docs, null, 2)};\n`);

console.log(`build-content: ${docs.length} docs → lib/content-index.json, public/docs-content.json, _data/docs-data.mjs`);
